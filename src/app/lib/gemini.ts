import { GoogleGenerativeAI } from "@google/generative-ai";

const apiKey = import.meta.env.VITE_GEMINI_API_KEY;

if (!apiKey) {
  console.error("🚨 [환경 변수 누락] VITE_GEMINI_API_KEY가 시스템에 존재하지 않습니다.");
}

const genAI = new GoogleGenerativeAI(apiKey || "MISSING_API_KEY");

export const analyzeDrawing = async (userInfo: any, imageBase64: string) => {
  if (!apiKey || apiKey === "MISSING_API_KEY") {
    throw new Error("Gemini API Key가 누락되었습니다. Vercel 환경 변수 설정을 확인해주세요.");
  }

  // 🌟 기존에 설정하신 모델 유지
  const model = genAI.getGenerativeModel({ model: "gemini-3.1-flash-lite" });
  
  const base64Data = imageBase64.split(",")[1];
  if (!base64Data) {
    throw new Error("올바르지 않은 이미지 데이터 형식입니다.");
  }

  let specificGuide = "";
  const testType = userInfo.testType || "";

  // 각 검사별 가이드라인 유지
  switch (testType) {
    case "rain":
      specificGuide = `
      이 이미지는 '빗속의 사람(PITR, Person In The Rain)' 검사 그림입니다. 다음 요소들을 이미지에서 세밀히 관찰하고, 이를 근거로 내담자의 '스트레스 수준과 대처 능력'을 분석해 주세요:
      - 비와 구름 (스트레스의 양과 성질): 비의 양, 굵기, 방향성(사선인지 수직인지), 웅덩이, 번개나 먹구름의 유무를 확인하세요.
      - 대처 자원 (스트레스 방어기제): 우산, 비옷, 장화, 가림막 등의 크기와 상태를 확인하세요. (예: 우산이 비를 충분히 가려주고 있는지, 우산이 찢어지거나 너무 작지 않은지)
      - 인물의 상태 (자아 강도 및 정서): 인물의 표정, 자세, 크기, 종이 내 위치를 확인하세요. 인물이 비를 맞고 있는지, 피하고 있는지, 비에도 불구하고 평온한지 등 환경과 인물의 '상호작용'을 중점적으로 분석하세요.
      - 필압과 선의 질: 선이 끊어지거나 떨리는지, 강박적으로 덧칠했는지 확인하여 불안감과 에너지를 유추하세요.
      `;
      break;
    case "starwave":
      specificGuide = `
      이 이미지는 '별과 파도(SWT, Stars and Waves Test)' 검사 그림입니다. 다음 요소들을 이미지에서 세밀히 관찰하고, 이를 근거로 내담자의 '이성적 지향점(희망)과 감성적 무의식(불안)'을 분석해 주세요:
      - 별의 형태와 배치 (이상향과 인지적 영역): 하늘에 떠 있는 별의 개수, 크기, 디테일(단순한 점인지, 정교한 별 모양인지), 종이 상단에서의 위치를 확인하세요.
      - 파도의 역동성 (무의식적 감정과 에너지): 파도의 높낮이, 뾰족함/부드러움, 선의 굴곡, 거칠기를 확인하세요. 파도가 규칙적인지 혼란스러운지 분석하세요.
      - 별과 파도의 간격과 상호작용: 별(이성)과 파도(감성) 사이의 여백이 얼마나 되는지, 파도가 별을 덮칠 듯이 위협적인지, 아니면 조화롭게 분리되어 있는지 분석하여 내적 갈등 여부를 유추하세요.
      - 추가 요소 (현실 지지 기반): 바위, 등대, 배, 달, 섬 등 기본 지시어 외에 그려진 지형지물이 있다면 이를 내담자의 현실적 지지 기반이나 장애물로 해석하세요
      `;
      break;
    case "hexagon":
      specificGuide = `
      이 이미지는 '육도형(6개의 분할된 칸)' 검사 그림입니다. 다음 요소들을 이미지에서 세밀히 관찰하고, 이를 근거로 내담자의 '인지적 균형과 심리적 에너지 분배 상태'를 분석해 주세요:
      - 공간 활용과 여백 (심리적 위축 및 개방성): 6개의 칸 중 어느 칸이 꽉 채워져 있고 어느 칸이 비어있는지, 특정 영역에 대한 회피나 과몰입이 있는지 확인하세요.
      - 도형 간의 조화와 선의 질: 각 칸에 그려진 그림들이 서로 연결성이나 일관성이 있는지, 선의 진하기(필압)가 칸마다 다른지 확인하여 에너지의 불균형을 분석하세요.
      - 경계선 침범 여부 (충동성 및 규칙 준수): 그려진 그림이 분할된 칸의 선을 넘어가는지, 아니면 칸 안에 강박적으로 갇혀 있는지 관찰하여 내담자의 통제력과 충동성을 유추하세요.
      - 형태의 상징성: 각 칸에 그려진 형태가 유기체(생명물)인지 무기체(사물, 기하학)인지 파악하여 정서적 유연성을 분석하세요.
      `;
      break;
    case "htp":
      specificGuide = `
      이 이미지는 '집-나무-사람(HTP, House-Tree-Person)' 검사 그림입니다. 다음 요소들을 이미지에서 세밀히 관찰하고, 이를 근거로 내담자의 '자아상, 대인관계, 무의식적 욕구'를 종합적으로 분석해 주세요:
      - 집 (가정 환경과 물리적 소통): 지붕(공상과 지적 영역), 문과 창문(타인과의 소통 개방성, 크기와 자물쇠 유무 확인), 굴뚝과 연기(가정 내 따뜻함 또는 억압된 갈등), 벽의 상태를 분석하세요.
      - 나무 (무의식적 성장 욕구와 생명력): 뿌리(현실 기반과 안정감), 줄기(자아 강도, 옹이나 상처 유무), 가지와 수관(환경에서 성취하려는 욕구, 잎의 풍성함)을 분석하세요.
      - 사람 (현실의 자아상): 크기, 성별, 표정, 손과 발(환경에 대한 통제력과 대처 수단), 생략되거나 과도하게 강조된 신체 부위가 있는지 확인하세요.
      - 통합적 구성 (Gestalt): 세 요소(집, 나무, 사람) 간의 거리, 상대적인 크기 비율, 종이 내에서의 위치(중앙, 치우침), '지면선(Ground line)'의 유무를 분석하여 전반적인 심리적 안정감과 현실 감각을 도출하세요.
      `;
      break;
    default:
      specificGuide = "그림에서 관찰되는 선의 형태, 크기, 배치를 객관적 시각적 근거로 삼아 분석해줘.";
  }

  // 🌟 AI에게 JSON 형식으로 응답하도록 엄격하게 지시합니다.
  const prompt = `
  너는 미술 치료 경력 15년 차의 임상 심리 전문가이자 따뜻한 공감을 전하는 상담가야.
  제공된 이미지를 전문가의 눈으로 정밀하게 스캔한 뒤 심리 분석 리포트를 작성해줘.

  [내담자 정보]
  - 연령: ${userInfo.age}
  - 성별: ${userInfo.gender}
  - 현재 하고 있는 일: ${userInfo.job}
  - 현재 고민: ${userInfo.concern}
  
  [분석 가이드라인]
  ${specificGuide}
  
  [★ 필수 답변 작성 규칙 - 신뢰성과 근거 강화]
  1. 절대 추측으로만 쓰지 마: 심리 상태를 설명할 때는 반드시 "그림에서 우산이 얼굴을 푹 덮을 만큼 크게 그려진 것을 보아"와 같이 그림 속 시각적 단서를 명확한 근거로 먼저 제시해줘.
  2. 말투와 톤앤매너: 15년 차 전문가답게 논리적이면서도, 내담자의 고민을 부드럽게 감싸안아 주는 다정하고 따뜻한 위로의 말투(해요체)를 유지해줘. 차가운 의학적 진단명은 절대 피할 것.
  3. 구조화: 그림 분석 시 
     - [1단계: 시각적 특징의 객관적 묘사, 내담자의 사연(고민)에 대한 진심 어린 공감과 첫인상] 
     - [2단계: 심리적 의미 해석, 그림의 구체적 특징(시각적 근거)과 그것이 뜻하는 내면의 상태 연결] 
     - [3단계: 종합 소견 및 긍정적 자원 찾기, 고민을 이겨내고 앞으로 나아가기 위한 따뜻한 조언]
  의 순서로 답변해 주세요. 단, 이 분석은 의학적 진단이 아님을 명시하세요.
  
  4. (가장 중요) 출력 형식: 반드시 아래의 JSON 형식으로만 응답해야 해. 마크다운 기호(\`\`\`json 등)는 일절 포함하지 마.
  {
    "keywords": ["맞춤키워드1", "맞춤키워드2", "맞춤키워드3", "맞춤키워드4"],
    "content": "1~3단계로 구성된 전체 본문 내용 (줄바꿈은 \\n 사용)"
  }
  `;

  try {
    const result = await model.generateContent([
      prompt,
      { inlineData: { data: base64Data, mimeType: "image/png" } }
    ]);
    
    // AI가 마크다운 블록을 붙여서 응답할 경우를 대비해 깔끔하게 제거합니다.
    const rawText = result.response.text();
    return rawText.replace(/```json/g, "").replace(/```/g, "").trim();
  } catch (apiError: any) {
    console.error("Gemini API 호출 내부 오류:", apiError);
    throw new Error("AI 분석 중 오류가 발생했습니다.");
  }
};